//! Public, deterministic credentials only for the local actor tests.
//!
//! These P-256 keys are intentionally public test values and must never be used
//! by an endpoint outside these tests. The CA scalar is [7; 32], the localhost
//! leaf scalar is [9; 32]. DER certificates were generated locally with Python
//! cryptography 50.0.0, deterministic ECDSA/SHA-256, serials 1 and 2, and validity
//! 2025-01-01 through 2035-01-01. The CA has CA/keyCertSign/cRLSign; the leaf has
//! digitalSignature/serverAuth and the localhost DNS SAN. No runtime trust or
//! authentication bypass is installed, and no test-time package is required.

use hibana_tls::certificate::UnixTime;
use hibana_tls::entropy::{Entropy, Unavailable};
use hibana_tls::handshake::SigningKey;
