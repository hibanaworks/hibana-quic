pub const CLIENT_PARAMS: &[u8] = &[4, 1, 42];
pub const SERVER_PARAMS: &[u8] = &[4, 1, 63];
pub fn signing_key() -> SigningKey {
    SigningKey::from_slice(&[9; 32]).unwrap()
}
pub fn now() -> UnixTime {
    UnixTime::since_unix_epoch(Duration::from_secs(1_800_000_000))
}
pub struct Buffers {
    rx: [u8; 8192],
    tx: [u8; 8192],
    certificates: [u8; 8192],
    parameters: [u8; 512],
}
impl Buffers {
    pub fn new() -> Self {
        Self {
            rx: [0; 8192],
            tx: [0; 8192],
            certificates: [0; 8192],
            parameters: [0; 512],
        }
    }
    pub fn storage(&mut self) -> Storage<'_> {
        Storage {
            rx_message: &mut self.rx,
            tx_flight: &mut self.tx,
            peer_certificates: &mut self.certificates,
            peer_parameters: &mut self.parameters,
        }
    }
}
/// Reproducible entropy for tests only; packet protection and certificate
/// authentication still use the production cryptographic implementation.
pub struct TestRandom(pub u64);
impl TestRandom {
    fn next_u64(&mut self) -> u64 {
        self.0 ^= self.0 << 13;
        self.0 ^= self.0 >> 7;
        self.0 ^= self.0 << 17;
        self.0
    }
    fn fill_bytes(&mut self, dest: &mut [u8]) {
        for part in dest.chunks_mut(8) {
            part.copy_from_slice(&self.next_u64().to_le_bytes()[..part.len()]);
        }
    }
}
impl Entropy for TestRandom {
    fn try_fill_bytes(&mut self, dest: &mut [u8]) -> Result<(), Unavailable> {
        self.fill_bytes(dest);
        Ok(())
    }
}

